namespace digitalastronaut\craftqrpayments\services;

use Craft;
use craft\base\Component;
use craft\web\Request;

use digitalastronaut\craftqrpayments\elements\Payment;
use digitalastronaut\craftqrpayments\models\PaymentType;
use digitalastronaut\craftqrpayments\QrPayments;

use DateTime;
use yii\base\Exception;

/**
 * Class PaymentsService
 *
 * @author      Digitalastronaut
 * @package     QrPayments
 * @since       v1.0.0-beta
 */
class PaymentsService extends Component {
    /**
     * @param PaymentType $type
     * @param float $amount
     * @param string $email
     * @param DateTime|null $dueDate
     * @param int|null $subscriptionId The subscription this payment was stamped out by, when called from `SubscriptionsService::advance()`. Null for a one-off payment.
     * @param int|null $userId The Craft user this payment is linked to, when the payer has an account. Null for a guest payment.
     * @return Payment
     * @throws Exception if the payment fails validation on save (including a bad beneficiary/IBAN/BIC EPC payload — see `Payment::generateQrCode()`)
     */
    public function createPayment(PaymentType $type, float $amount, string $email, ?DateTime $dueDate = null, ?int $subscriptionId = null, ?int $userId = null): Payment {
        $payment = new Payment();
        $payment->typeId = $type->id;
        $payment->subscriptionId = $subscriptionId;
        $payment->userId = $userId;
        $payment->email = $email;
        $payment->amount = $amount;

        if ($dueDate !== null) $payment->dueDate = $dueDate;

        // Only pull custom field values from an actual form submission —
        // a console/queue-triggered call (e.g. SubscriptionsService::advance())
        // has no request to pull them from, and craft\console\Request
        // doesn't even implement getBodyParam().
        if (Craft::$app->getRequest() instanceof Request) {
            $payment->setFieldValuesFromRequest('fields');
        }

        // Everything else — beneficiary/IBAN/BIC, the unique reference, the
        // QR code, the "payment created" notification — is generated by
        // `Payment` itself on its first real save (see `Payment::beforeValidate()`/
        // `beforeSave()`/`afterSave()`), the same way the native CP "New
        // payment" draft flow creates one.
        if (!Craft::$app->getElements()->saveElement($payment)) {
            throw new Exception(sprintf(
                'Failed to create payment: %s',
                json_encode($payment->getErrors())
            ));
        }

        return $payment;
    }

    /**
     * @param string $prefix
     * @return string
     */
    public function generateUniqueReference(string $prefix): string {
        $qrPayments = QrPayments::getInstance();

        do {
            $reference = $qrPayments->getEpcQr()->generateRfReference($this->referenceBody($prefix));
        } while (Payment::find()->remittanceReference($reference)->exists());

        return $reference;
    }

    /**
     * @param string $prefix
     * @return string
     */
    private function referenceBody(string $prefix): string {
        $prefix = substr(strtoupper(preg_replace('/[^A-Z0-9]/i', '', $prefix)), 0, 12);
        $random = strtoupper(bin2hex(random_bytes(4)));

        return substr($prefix . $random, 0, 21);
    }
}
