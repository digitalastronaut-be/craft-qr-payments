namespace digitalastronaut\craftqrpayments\services;

use Craft;
use craft\base\Component;

use Endroid\QrCode\Builder\Builder;
use Endroid\QrCode\Encoding\Encoding;
use Endroid\QrCode\ErrorCorrectionLevel;
use Endroid\QrCode\Writer\PngWriter;
use Endroid\QrCode\Writer\Result\ResultInterface;

use SepaQr\SepaQrData;

use InvalidArgumentException;

use function iban_checksum_string_replace;
use function iban_country_is_sepa;
use function iban_get_country_part;
use function iban_mod97_10;
use function iban_mod97_10_checksum;
use function verify_iban;

/**
 * Class EpcQrService
 *
 * Builds EPC069-12 ("SEPA Credit Transfer") QR code payloads and renders
 * them as scannable QR codes. Payload generation and validation is
 * delegated to smhg/sepa-qr-data; rendering to endroid/qr-code.
 *
 * @author      Digitalastronaut
 * @package     QrPayments
 * @since       v1.0.0-beta
 */
class EpcQrService extends Component {
    /**
     * Verifies an IBAN's checksum and country format (via
     * globalcitizen/php-iban) and that it belongs to a SEPA country.
     * Shared by generatePayload() and by Settings, so a misconfigured
     * beneficiary IBAN is reported with the same descriptive message
     * whether it's caught while saving plugin settings or while building
     * a QR code.
     *
     * @param string $iban
     * @return void
     * @throws InvalidArgumentException if the IBAN is malformed or isn't from a SEPA country.
     */
    public function validateIban(string $iban): void {
        $iban = strtoupper(str_replace(' ', '', $iban));

        if (!verify_iban($iban, true)) {
            throw new InvalidArgumentException(Craft::t('qr-payments', 'Invalid IBAN: {iban}.', ['iban' => $iban]));
        }

        if (!iban_country_is_sepa(iban_get_country_part($iban))) {
            throw new InvalidArgumentException(
                Craft::t('qr-payments', 'IBAN {iban} is not from a SEPA country. EPC QR payments only support SEPA credit transfers.', 
                ['iban' => $iban]
            ));
        }
    }

    /**
     * Builds an ISO 11649 "RF Creditor Reference" from an arbitrary
     * alphanumeric body — the format the EPC QR standard's structured
     * remittance line (AT-05) actually expects, as opposed to the Belgian
     * national OGM/VCS scheme, which isn't valid there. The check digits
     * use the same ISO 7064 MOD 97-10 algorithm as an IBAN checksum
     * (`globalcitizen/php-iban` already implements it), just applied to
     * `$body . 'RF00'` instead of a BBAN.
     *
     * @param string $body Alphanumeric reference body, max 21 characters.
     * @return string The full reference, e.g. `RF18539007547034`.
     * @throws InvalidArgumentException if the body is empty or longer than 21 characters.
     */
    public function generateRfReference(string $body): string {
        if ($body === '') {
            throw new InvalidArgumentException('A creditor reference body is required.');
        }

        if (strlen($body) > 21) {
            throw new InvalidArgumentException("Invalid creditor reference body: {$body}. Should be maximum 21 characters.");
        }

        $numeric = iban_checksum_string_replace($body . 'RF00');
        $checkDigits = str_pad((string) (98 - iban_mod97_10_checksum($numeric)), 2, '0', STR_PAD_LEFT);

        return "RF{$checkDigits}{$body}";
    }

    /**
     * Verifies that a string is a shape- and checksum-valid ISO 11649 RF
     * Creditor Reference — used to filter real reference matches out of
     * free-text bank export contents in `ReconciliationService`, since a
     * bare `/RF\d{2}.../` regex would also accept any lookalike text that
     * happens to fit the shape but was never actually generated by us.
     *
     * @param string $reference
     * @return bool
     */
    public function isValidRfReference(string $reference): bool {
        $reference = strtoupper(str_replace(' ', '', $reference));

        if (!preg_match('/^RF\d{2}[A-Z0-9]{1,21}$/', $reference)) return false;

        $rearranged = substr($reference, 4) . substr($reference, 0, 4);

        return iban_mod97_10(iban_checksum_string_replace($rearranged));
    }

    /**
     * Builds and validates the EPC payload text. Beyond the length/shape
     * checks smhg/sepa-qr-data already does, this also verifies the IBAN's
     * checksum and country format (via globalcitizen/php-iban) and that it
     * belongs to a SEPA country — a merely correct-length IBAN would
     * otherwise sail straight into a QR code that only fails once someone
     * actually tries to pay it.
     *
     * The EPC standard requires error correction level M.
     *
     * @param string $beneficiaryName
     * @param string $iban
     * @param float $amount
     * @param string|null $bic Required outside the EEA, optional within it (SEPA QR version 2).
     * @param string|null $remittanceReference Structured reference (e.g. an RF creditor reference), max 35 chars. Mutually exclusive with $remittanceText.
     * @param string|null $remittanceText Unstructured remittance text, max 140 chars. Mutually exclusive with $remittanceReference.
     * @param string|null $purpose 4-character SEPA purpose code, e.g. "GDDS".
     * @param string|null $information Beneficiary-to-originator information, max 70 chars.
     * @return string The raw EPC QR payload text.
     * @throws InvalidArgumentException if the IBAN is malformed or isn't from a SEPA country.
     */
    public function generatePayload(
        string $beneficiaryName,
        string $iban,
        float $amount,
        ?string $bic = null,
        ?string $remittanceReference = null,
        ?string $remittanceText = null,
        ?string $purpose = null,
        ?string $information = null,
    ): string {
        $iban = strtoupper(str_replace(' ', '', $iban));

        $this->validateIban($iban);

        $data = new SepaQrData();

        $data->setName($beneficiaryName);
        $data->setIban($iban);
        $data->setAmount($amount);

        if ($bic !== null) $data->setBic($bic);
        if ($remittanceReference !== null) $data->setRemittanceReference($remittanceReference);
        if ($remittanceText !== null) $data->setRemittanceText($remittanceText);
        if ($purpose !== null) $data->setPurpose($purpose);
        if ($information !== null) $data->setInformation($information);

        return (string) $data;
    }

    /**
     * @param string $beneficiaryName
     * @param string $iban
     * @param float $amount
     * @param string|null $bic
     * @param string|null $remittanceReference
     * @param string|null $remittanceText
     * @param string|null $purpose
     * @param string|null $information
     * @param int $size QR code size in pixels.
     * @param int $margin QR code margin in pixels.
     * @return ResultInterface Renderer result — call ->getString(), ->getDataUri() or ->saveToFile() on it.
     */
    public function generateQrCode(
        string $beneficiaryName,
        string $iban,
        float $amount,
        ?string $bic = null,
        ?string $remittanceReference = null,
        ?string $remittanceText = null,
        ?string $purpose = null,
        ?string $information = null,
        int $size = 300,
        int $margin = 10,
    ): ResultInterface {
        $payload = $this->generatePayload(
            $beneficiaryName,
            $iban,
            $amount,
            $bic,
            $remittanceReference,
            $remittanceText,
            $purpose,
            $information,
        );

        $builder = new Builder(
            writer: new PngWriter(),
            data: $payload,
            encoding: new Encoding('UTF-8'),
            errorCorrectionLevel: ErrorCorrectionLevel::Medium,
            size: $size,
            margin: $margin,
        );

        return $builder->build();
    }
}
